import { readFile, readdir, mkdir, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { marked } from "marked";

const scriptDirectory = path.dirname(fileURLToPath(import.meta.url));
const rootDirectory = path.resolve(scriptDirectory, "..");
const projectsDirectory = path.join(rootDirectory, "src", "projects");
const layoutsDirectory = path.join(rootDirectory, "src", "layouts");
const includesDirectory = path.join(rootDirectory, "src", "includes");

const escapeHtml = (value = "") => String(value)
  .replaceAll("&", "&amp;")
  .replaceAll("<", "&lt;")
  .replaceAll(">", "&gt;")
  .replaceAll('"', "&quot;")
  .replaceAll("'", "&#039;");

function parseFrontMatter(source, fileName) {
  const match = source.match(/^---\r?\n([\s\S]*?)\r?\n---\r?\n/);
  if (!match) throw new Error(`${fileName} is missing front matter.`);

  const metadata = {};
  for (const line of match[1].split(/\r?\n/)) {
    const separator = line.indexOf(":");
    if (separator === -1) continue;
    const key = line.slice(0, separator).trim();
    const value = line.slice(separator + 1).trim();
    metadata[key] = value;
  }

  return { metadata, body: source.slice(match[0].length) };
}

async function resolveIncludes(source) {
  const includePattern = /\{%\s*include\s+([^\s%]+)\s*%\}/g;
  let result = source;
  let match;

  while ((match = includePattern.exec(result)) !== null) {
    const includePath = path.resolve(includesDirectory, match[1]);
    if (!includePath.startsWith(`${includesDirectory}${path.sep}`)) {
      throw new Error(`Invalid include path: ${match[1]}`);
    }

    const includeContent = await readFile(includePath, "utf8");
    result = `${result.slice(0, match.index)}${includeContent}${result.slice(match.index + match[0].length)}`;
    includePattern.lastIndex = 0;
  }

  return result;
}

function applyLayout(layout, metadata, content) {
  const values = {
    title: escapeHtml(metadata.title),
    description: escapeHtml(metadata.description),
    lead: escapeHtml(metadata.lead),
    date: escapeHtml(metadata.date),
    back_url: escapeHtml(metadata.back_url || "../projects.html"),
    back_label: escapeHtml(metadata.back_label || "Projects"),
    content
  };

  return layout.replace(/\{\{\s*([a-z_]+)\s*\}\}/g, (_, key) => values[key] ?? "");
}

async function buildProject(sourcePath) {
  const source = await readFile(sourcePath, "utf8");
  const { metadata, body } = parseFrontMatter(source, path.basename(sourcePath));

  for (const field of ["layout", "title", "description", "lead", "date", "output"]) {
    if (!metadata[field]) throw new Error(`${path.basename(sourcePath)} is missing '${field}'.`);
  }

  const expandedBody = await resolveIncludes(body);
  const content = await marked.parse(expandedBody, { gfm: true });
  const layoutPath = path.join(layoutsDirectory, `${metadata.layout}.html`);
  const layout = await readFile(layoutPath, "utf8");
  const output = `<!-- Generated by npm run build. Edit ${path.relative(rootDirectory, sourcePath).replaceAll("\\", "/")} instead. -->\n${applyLayout(layout, metadata, content)}`;
  const outputPath = path.resolve(rootDirectory, metadata.output);

  if (!outputPath.startsWith(`${rootDirectory}${path.sep}`)) {
    throw new Error(`Invalid output path: ${metadata.output}`);
  }

  await mkdir(path.dirname(outputPath), { recursive: true });
  await writeFile(outputPath, output, "utf8");
  return path.relative(rootDirectory, outputPath).replaceAll("\\", "/");
}

const projectFiles = (await readdir(projectsDirectory))
  .filter((fileName) => fileName.endsWith(".md") && !fileName.startsWith("_"))
  .sort();

if (!projectFiles.length) throw new Error("No project source files were found.");

for (const projectFile of projectFiles) {
  const outputPath = await buildProject(path.join(projectsDirectory, projectFile));
  console.log(`Built ${outputPath}`);
}
